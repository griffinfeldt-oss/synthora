// Builds the adapter registries from the files on disk, so adding a partner or
// a model is one new file. Runs before dev, build, typecheck and test.
import { readdirSync, writeFileSync, existsSync, readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function generate({ dir, out, type, typeImport, exportName }) {
  const abs = join(root, dir);
  const files = readdirSync(abs)
    .filter((f) => f.endsWith(".ts") && !f.endsWith(".test.ts") && !f.startsWith("_"))
    .sort();
  const names = files.map((f) => f.replace(/\.ts$/, "").replace(/[^a-zA-Z0-9]/g, "_"));
  const body = [
    "// AUTO-GENERATED by scripts/gen-registries.mjs. Do not edit.",
    `import type { ${type} } from "${typeImport}";`,
    ...files.map((f, i) => `import ${names[i]} from "./${dir.split("/").pop()}/${f.replace(/\.ts$/, "")}";`),
    "",
    `export const ${exportName}: ${type}[] = [${names.join(", ")}];`,
    "",
  ].join("\n");
  const outPath = join(root, out);
  if (!existsSync(outPath) || readFileSync(outPath, "utf8") !== body) writeFileSync(outPath, body);
  console.log(`registry: ${out} ← ${files.length} adapters (${names.join(", ")})`);
}

generate({
  dir: "src/fulfillment/adapters",
  out: "src/fulfillment/registry.generated.ts",
  type: "FulfillmentProvider",
  typeImport: "./types",
  exportName: "ALL_PROVIDERS",
});
generate({
  dir: "src/ai/image",
  out: "src/ai/image-registry.generated.ts",
  type: "ImageModel",
  typeImport: "./types",
  exportName: "ALL_IMAGE_MODELS",
});
